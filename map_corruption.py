"""Determine the exact corruption mapping to fix opportunity-radar.html."""
import os, re
os.chdir(r"c:\Users\ASUS\OneDrive\Desktop\hacknHills\AURORA-website (1)\AURORA")

with open('opportunity-radar.html', 'rb') as f:
    raw = f.read()

decoded = raw.decode('utf-8')

# The title has: AURORA Γö Opportunity Radar
# We know it should be: AURORA — Opportunity Radar  (em-dash)
# U+2014 em-dash in UTF-8 = E2 80 94
# What does the file have instead?
# CE 93 = Γ, C3 87 = Ç, C3 B6 = ö

# Let's work backward:
# If ΓÇö were actually individual bytes 0x93, 0x87, 0xB6... 
# Wait: Γ(U+0393) was encoded from byte 0x93 via: 0x93 in CP1252 is ' (left curly quote)
# But how does a single byte become 2 UTF-8 bytes?
# Answer: if you read CP1252 file byte-by-byte, replace each byte with its Unicode codepoint,
# then re-encode as UTF-8, you get double-byte sequences for high bytes.

# Original byte -> CP1252/Latin-1 interpretation -> UTF-8 encoding
# 0xE2 -> â (U+00E2) -> C3 A2
# 0x80 -> (in CP1252 this is €, U+20AC) -> E2 82 AC
# 0x94 -> (in CP1252 this is ", U+201D) -> E2 80 9D
# Hmm, that gives E2 80 — 3 different byte sequences, not CE93 C387 C3B6

# Let me try pure Latin-1 interpretation:
# 0xE2 -> U+00E2 (â) -> UTF-8: C3 A2
# 0x80 -> U+0080 (control) -> UTF-8: C2 80  
# 0x94 -> U+0094 (control) -> UTF-8: C2 94
# Total: C3 A2 C2 80 C2 94 -- not matching

# Try: what if the corruption happened the OTHER way:
# The file HAD correct Unicode codepoints (Γ, Ç, ö etc.) but they SHOULD have been 
# rupee, em-dash etc.? That is: someone did a bad regex replacement or 
# loaded the file in wrong encoding and saved.
# 
# Key: Γ = U+0393. If I encode it as Latin-1: 0xCE, 0x93 (but Latin-1 can't encode U+0393)
# If I encode Γ as Windows-1252: also can't
# If I encode Γ as UTF-8: CE 93 -- this IS the bytes in the file!
# 
# So the file IS valid UTF-8, and it CONTAINS U+0393 Γ characters.
# These Γ characters replaced what should have been ₹ (U+20B9).
# 
# HOW: The file was read as UTF-8 (correctly giving ₹), then written somewhere
# that truncated to single-byte chars (dropping 2 of the 3 bytes), OR
# the ₹ symbol (E2 82 B9) was interpreted as 3 Latin-1 characters: â, ‚, ¹
# then those 3 Latin-1 chars were somehow mapped differently...
# 
# Actually the simplest explanation: this file was regenerated by a tool that
# had incorrect Unicode handling. The file simply does NOT have the right characters.
# We need to replace the wrong chars with right ones.

# Step 1: Find ALL instances of Γ (U+0393) and what surrounds them to understand the mapping
gamma = chr(0x0393)
c_cedilla = chr(0x00C7)
o_umlaut = chr(0x00F6)

print("=== Gamma (U+0393) contexts ===", file=open('map_analysis.txt','w', encoding='utf-8'))

with open('map_analysis.txt', 'a', encoding='utf-8') as out:
    # Sample 20 contexts with Gamma
    gamma_positions = [m.start() for m in re.finditer(re.escape(gamma), decoded)]
    out.write(f"Total Gamma: {len(gamma_positions)}\n")
    
    # Look at 2-char sequences involving Gamma
    gamma_pairs = {}
    for pos in gamma_positions:
        if pos + 1 < len(decoded):
            pair = decoded[pos:pos+2]
            gamma_pairs[pair] = gamma_pairs.get(pair, 0) + 1
    
    out.write("\nGamma + next char combos:\n")
    for pair, count in sorted(gamma_pairs.items(), key=lambda x: -x[1]):
        pair_hex = ' '.join(f'{ord(c):04X}' for c in pair)
        out.write(f"  {repr(pair)} ({pair_hex}) x{count}\n")
    
    out.write("\n\nSample contexts with Gamma:\n")
    for pos in gamma_positions[:30]:
        ctx = decoded[max(0, pos-10):pos+20]
        ctx_hex = ' '.join(f'{ord(c):02X}' for c in ctx)
        out.write(f"  pos={pos}: {repr(ctx)}\n")
        out.write(f"         hex: {ctx_hex}\n")

print("Done")
